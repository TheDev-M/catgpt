-- Baseline schema for CatGPT.
--
-- Generated from the JPA entities with the PostgreSQL dialect so that it matches
-- exactly what `spring.jpa.hibernate.ddl-auto: validate` expects. Existing
-- databases created by the previous `ddl-auto: update` setting are stamped at
-- this version by `spring.flyway.baseline-on-migrate`, so this script only ever
-- runs against a fresh database.
--
-- From here on the schema is owned by migrations, not by Hibernate: every change
-- to an entity needs a matching V<n>__*.sql file.

CREATE TABLE users
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version         BIGINT,
    created_at      TIMESTAMP(6) WITH TIME ZONE,
    updated_at      TIMESTAMP(6) WITH TIME ZONE,
    username        VARCHAR(64)  NOT NULL UNIQUE,
    password_hash   VARCHAR(255),
    email           VARCHAR(320) UNIQUE,
    auth_provider   VARCHAR(16)  NOT NULL CHECK (auth_provider IN ('LOCAL', 'GOOGLE')),
    description     VARCHAR(512),
    nickname        VARCHAR(64),
    selected_cat_id BIGINT,
    last_own_cat_id BIGINT,
    last_visit      TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id)
);

CREATE TABLE cats
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version        BIGINT,
    created_at     TIMESTAMP(6) WITH TIME ZONE,
    updated_at     TIMESTAMP(6) WITH TIME ZONE,
    name           VARCHAR(64) NOT NULL,
    breed          VARCHAR(64) NOT NULL,
    hunger         INTEGER,
    mood           INTEGER,
    health         INTEGER,
    image          TEXT,
    owner_id       BIGINT      NOT NULL,
    default_cat    BOOLEAN     NOT NULL,
    borrowed_by_id BIGINT,
    borrowed_at    TIMESTAMP(6) WITH TIME ZONE,
    PRIMARY KEY (id),
    CONSTRAINT uk_cats_owner_name UNIQUE (owner_id, name),
    CONSTRAINT fk_cats_owner FOREIGN KEY (owner_id) REFERENCES users,
    CONSTRAINT fk_cats_borrowed_by FOREIGN KEY (borrowed_by_id) REFERENCES users
);

CREATE TABLE cat_temperaments
(
    cat_id      BIGINT      NOT NULL,
    temperament VARCHAR(32) NOT NULL,
    PRIMARY KEY (cat_id, temperament),
    CONSTRAINT fk_cat_temperaments_cat FOREIGN KEY (cat_id) REFERENCES cats
);

CREATE TABLE items
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version          BIGINT,
    created_at       TIMESTAMP(6) WITH TIME ZONE,
    updated_at       TIMESTAMP(6) WITH TIME ZONE,
    name             VARCHAR(16) NOT NULL,
    category         VARCHAR(16) NOT NULL CHECK (category IN ('FOOD', 'HYGIENE', 'TOY')),
    stat             VARCHAR(16) NOT NULL CHECK (stat IN ('HUNGER', 'MOOD', 'HEALTH')),
    amount           INTEGER     NOT NULL,
    available_amount INTEGER     NOT NULL,
    owner_id         BIGINT      NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_items_owner FOREIGN KEY (owner_id) REFERENCES users
);

CREATE TABLE friendships
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version      BIGINT,
    created_at   TIMESTAMP(6) WITH TIME ZONE,
    updated_at   TIMESTAMP(6) WITH TIME ZONE,
    requester_id BIGINT      NOT NULL,
    receiver_id  BIGINT      NOT NULL,
    status       VARCHAR(16) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED')),
    PRIMARY KEY (id),
    CONSTRAINT uk_friendships_requester_receiver UNIQUE (requester_id, receiver_id),
    CONSTRAINT fk_friendships_requester FOREIGN KEY (requester_id) REFERENCES users,
    CONSTRAINT fk_friendships_receiver FOREIGN KEY (receiver_id) REFERENCES users
);

-- Foreign keys are not indexed automatically in PostgreSQL, and every one of
-- these columns is filtered on by a hot query (a user's cats, a user's items,
-- a user's friendships, the borrow lookups).
CREATE INDEX idx_cats_owner ON cats (owner_id);
CREATE INDEX idx_cats_borrowed_by ON cats (borrowed_by_id);
CREATE INDEX idx_items_owner ON items (owner_id);
CREATE INDEX idx_friendships_requester ON friendships (requester_id);
CREATE INDEX idx_friendships_receiver ON friendships (receiver_id);
